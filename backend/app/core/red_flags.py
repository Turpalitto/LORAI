def scan(text: str) -> list[dict]:
    """Вернуть сработавшие флаги для произвольного текста (запрос/симптомы)."""
    t = (text or "").lower()
    out = []
    for f in RED_FLAGS:
        if any(k in t for k in f["match"]):
            out.append({"id": f["id"], "sign": f["sign"], "action": f["action"]})
    return out
