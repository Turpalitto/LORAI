"""ПДн-фильтр входящих запросов.

Раньше был список из 5 подстрок, который пропускал полис ОМС, дату рождения
и паспорт-серию без слова «паспорт». Форматы: СНИЛС, полис ОМС (16 цифр),
дата рождения, телефон РФ, паспорт РФ, длинные цифровые ID. Слово
«снилс/полис» тоже триггерит независимо от формата.

Фильтр стоит на входе `/chat` и `/chat/stream`: клинический вопрос не должен
уходить в LLM вместе с идентификаторами пациента.
"""
import re

PII_WARNING = "Не вводите персональные данные пациента!"

_PII_RX = [
    re.compile(r"\b\d{3}-\d{3}-\d{3}\s*\d{2}\b"),          # СНИЛС 123-456-789 00
    re.compile(r"\b\d{4}\s?\d{4}\s?\d{4}\s?\d{4}\b"),      # полис ОМС 16 цифр
    re.compile(r"\b\d{2}\.\d{2}\.(19|20)\d{2}\b"),         # дата рождения 01.02.1990
    # Телефон РФ. Раньше между кодом и номером допускался ОДИН разделитель,
    # поэтому «8 (912) 345-67-89» — самый частый формат — не ловился вообще.
    # Теперь разделители любые и в любом количестве, но каждая группа цифр
    # строго на своём месте, чтобы дозировка «8 500 мг … 10 дней» не считалась
    # телефоном.
    re.compile(r"(?:\+7|8)[\s\-\(]*\d{3}[\s\-\)]*\d{3}[\s\-]*\d{2}[\s\-]*\d{2}(?!\d)"),
    re.compile(r"\b\d{2}\s?\d{2}\s?№?\s?\d{6}\b"),         # паспорт РФ 99 99 №123456
    # Словесные маркеры. «фамилия» из списка убрана: это обычное слово
    # клинического вопроса («фамилия врача в протоколе», «фамилия не указана»),
    # и такой запрос блокировался целиком, хотя ПДн в нём нет. Фамилия-пример
    # остаётся («Иванов»), остальные форматы ловятся регулярками выше.
    re.compile(r"\bснилс\b|\bполис\b|\bпаспорт\b|\bиванов[ауы]?\b", re.I),
    # ФИО с инициалами: «Сидоров С.С.». Раньше ловился только пример «Иванов»,
    # поэтому реальное ФИО проходило в LLM. Требуем фамилию и хотя бы одну
    # инициалу с точкой — обычный текст так не выглядит.
    re.compile(r"\b[А-ЯЁ][а-яё]{2,}\s+[А-ЯЁ]\.\s?(?:[А-ЯЁ]\.)?"),
]


def has_pii(text: str) -> bool:
    return any(rx.search(text or "") for rx in _PII_RX)
