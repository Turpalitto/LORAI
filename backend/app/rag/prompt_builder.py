SYSTEM = """Ты — справочный ассистент ЛОР-врача. Отвечай ТОЛЬКО на основе КОНТЕКСТА ниже.
Запрещено домысливать дозировки, коды МКБ, схемы лечения. Каждый фактический тезис сопровождай
ссылкой [Документ: <название>, Раздел: <раздел>, Стр. <N>]. Если контекста недостаточно — так и скажи.
Не переноси дозировки, схемы и сроки из одного протокола в другой: данные другого заболевания
приводи только как явно помеченное сравнение.
В конце: "Инструмент справочный. Решение принимает врач."
НЕ обрабатывай персональные данные пациента — предупреди об этом."""
def build_prompt(query: str, chunks: list[dict]) -> tuple[str, str]:
    docs = sorted({c.get("document") or c.get("title") or c.get("nosology", "") for c in chunks})
    # Кросс-документный синтез (Excellence-1): явно требуем атрибуции —
    # какая часть ответа из какого документа, если источников несколько.
    # Формулировка раньше звучала как «сопоставь данные из разных документов
    # в одном ответе» и подталкивала смешивать соседние нозологии (в топ-6
    # регулярно попадают лечение синусита и наружного отита на вопрос про
    # средний отит). Теперь синтез разрешён, а перенос фактов между
    # заболеваниями прямо запрещён.
    multi = ""
    if len(docs) > 1:
        multi = ("\nКОНТЕКСТ ИЗ НЕСКОЛЬКИХ ДОКУМЕНТОВ:\n"
                 + "\n".join(f"- {d}" for d in docs)
                 + "\nОтвечай по тому заболеванию, о котором спросил врач. Другие документы"
                   " используй только как помеченное сравнение и не переноси из них"
                   " дозировки, схемы и сроки.")
    ctx = "\n\n".join(f"--- Источник {i+1} ---\nДокумент: {c.get('document') or c.get('title') or c.get('nosology','')}\n"
        f"Раздел: {c.get('section','')}\nСтраницы: {c.get('page_range','')}\nТекст: {c.get('text','')[:2000]}"
        for i, c in enumerate(chunks))
    user = f"КОНТЕКСТ:\n{ctx}\n{multi}\n\nВОПРОС ВРАЧА: {query}\n\nОтвет со ссылками на источники."
    return SYSTEM, user
