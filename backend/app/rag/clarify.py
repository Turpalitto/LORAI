"""Умные уточняющие вопросы (Excellence-1).

Вместо гадания при неполном запросе возвращаем конкретный вопрос.
Эвристики только на основе явных пробелов, без LLM-вызова:
- дозировка без веса/возраста;
- детский вопрос без возраста;
- симптом без локализации/длительности (только если запрос очень короткий).
"""
import re

_DOSAGE_RX = re.compile(r"доз|мг\b|мл\b|калькул|сколько (давать|принимать|пить|колоть)", re.I)
_WEIGHT_RX = re.compile(r"\bкг\b|\bг\b.*вес|вес.*\bг\b|мг/кг", re.I)
_AGE_RX = re.compile(
    r"(\d+\s*(лет|год|мес|нед|дн[ейя]?))|(реб[её]н(ок|ку|ка)|взросл|детск|груднич|подрост)",
    re.I,
)
_CHILD_RX = re.compile(r"реб[её]н|детск|груднич|подрост|младен", re.I)
_LOС_RX = re.compile(r"ухо|нос|горл|пазух|миндалин|слева|справа|двусторон", re.I)


def clarifying_question(query: str) -> str | None:
    q = (query or "").strip()
    if len(q) < 3:
        return "Уточните, пожалуйста, вопрос: какая нозология или симптом интересует?"
    if _DOSAGE_RX.search(q) and not _WEIGHT_RX.search(q):
        if _CHILD_RX.search(q) and not re.search(r"\d+\s*(лет|год|мес)", q, re.I):
            return (
                "Чтобы рассчитать дозу для ребёнка, уточните возраст "
                "и вес (например, «5 лет, 18 кг») и препарат."
            )
        return (
            "Чтобы рассчитать дозу, уточните вес пациента "
            "(например, «70 кг») и препарат."
        )
    if _CHILD_RX.search(q) and not _AGE_RX.search(q) and len(q.split()) <= 6:
        return "Уточните возраст ребёнка (например, «3 года»), чтобы дать точную рекомендацию."
    return None
