import re
REFUSAL = "В загруженных клинических рекомендациях информация по этому вопросу не найдена."
def check_numbers(answer: str, chunks: list[dict]) -> str:
    nums = set(re.findall(r"\d+(?:[.,]\d+)?\s*(?:мг|мл|г|мкг|МЕ|%)?", answer))
    ctx = " ".join(c.get("text","") for c in chunks)
    bad = [n for n in nums if n.strip() and n.strip().split()[0] not in ctx]
    if bad:
        return answer + "\n\n⚠️ Числа требуют проверки врачом: " + ", ".join(bad[:5])
    return answer


def norm_query(q: str) -> str:
    """Приводим вопрос к сравнимому виду: регистр и «ё» (иначе «ребёнка» не
    находил маркер «ребен», а «глотании» — «глотк»)."""
    return (q or "").lower().replace("ё", "е")


# Маркеры предметной области (ЛОР). Вопрос без единого маркера считается
# вне базы знаний независимо от скора: общие слова («лечение», «диагностика»)
# иначе дают ложное сходство с любым протоколом.
#
# Список пополнен по факту замера: 5 из 30 реальных ЛОР-вопросов получали
# отказ («тризм и боль при глотании», «эпиглоттит», «круп», «паратонзиллярный
# абсцесс») — в наборе не было их лексики (см. docs/RETRIEVAL_EVAL.md).
LOR_MARKERS = [
    # ухо/слух
    "отит", "отоскоп", "тугоухост", "слух", "ух", "уш", "барабанн", "евстахи", "звон", "звен",
    "лабиринтит", "неврит слухов", "тимпано", "мастоидит", "отосклероз", "оторея",
    "ушная раковин", "серн", "тиннитус", "ушной шум",
    # глотка/гортань/голос
    "тонзилл", "миндалин", "глотк", "глотани", "заглоточ", "парафар",
    "тризм", "флегмон", "ангин", "фарингит", "ларингит", "эпиглотт",
    "стридор", "ларингоспазм", "гортан", "голос", "дисфон", "осиплост", "афони",
    "кашел", "лающ", "слюнотечен", "треножник", "шепот", "храп", "апноэ", "оталг",
    # нос/пазухи
    "рин", "насморк", "залож", "перегородк", "полип", "пазух", "гаймор",
    "синусит", "фронтит", "этмоидит", "сфеноидит", "обоняни", "ринорея", "нос", "носов",
    "аденоид", "аденотом",
    # общее ЛОР + вестибулярное
    "лор", "оториноларинг", "вестибуляр", "головокружен", "нистагм", "отоневролог",
    # Лекарства из ЛОР-протоколов и дозировочная лексика: вопрос «доза
    # амоксициллина ребёнку» — легитимный, скор-гейт отсекает вне-доменные
    # совпадения.
    "амоксициллин", "азитромицин", "цефтриаксон", "цефиксим", "кларитромицин",
    "отипакс", "називин", "изофра", "полидекса", "софрадекс", "анауран",
    "доза", "дозировк", "мг/кг", "ребен", "детск", "педиатр",
]
ICD_LOR = re.compile(r"\b([HJ]\d{2}(?:\.\d{1,2})?|C3[012]|C73)\b", re.IGNORECASE)

# Маркеры длиной ≥5 символов ищем как подстроку (они специфичны: «тонзилл»
# находится и в «паратонзиллярном»), короткие — только с начала слова, иначе
# «флорист» дал бы «лор», а «перенос» — «нос».
_LONG_MARKERS = [m for m in LOR_MARKERS if len(m) >= 5]
_SHORT_MARKERS = [m for m in LOR_MARKERS if len(m) < 5]
_LONG_RX = re.compile("|".join(re.escape(m) for m in _LONG_MARKERS))
_SHORT_RX = re.compile(r"(?<![а-яa-z0-9])(?:" + "|".join(re.escape(m) for m in _SHORT_MARKERS) + ")")


def has_lor_signal(query: str) -> bool:
    q = norm_query(query)
    if ICD_LOR.search(q):
        return True
    return bool(_LONG_RX.search(q) or _SHORT_RX.search(q))


def effective_threshold(backend: str) -> float:
    """Порог скора зависит от шкалы бэкенда.

    TF-IDF даёт 0.11–0.60 по релевантным вопросам и 0.06–0.09 по нерелевантным,
    поэтому порог 0.12 работает как фильтр. У e5-эмбеддингов своя шкала: даже
    «инфаркт миокарда» набирает 0.83–0.85, то есть порог там домены НЕ
    разделяет — разделяет домен-гейт выше. Поэтому для эмбеддингов берём порог
    ниже минимума in-domain скоров (0.84), чтобы не отказывать ложно
    (измерения: docs/RETRIEVAL_EVAL.md)."""
    try:
        from ..core.config import settings
        return settings.EMBEDDING_THRESHOLD if backend == "embeddings" else settings.LLM_THRESHOLD
    except Exception:
        return 0.12


def should_refuse(chunks: list[dict], threshold: float, query: str | None = None) -> bool:
    if not chunks:
        return True
    top = max((c.get("score", 0) for c in chunks), default=0)
    if top < threshold:
        return True
    # Домен-гейт: нет ЛОР-сигнала в вопросе → честный отказ, даже если
    # скор выше порога за счёт общеупотребительных слов.
    if query is not None and not has_lor_signal(query):
        return True
    return False
