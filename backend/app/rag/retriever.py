import re
def classify_intent(q: str) -> str:
    l = q.lower()
    if re.search(r"доз|мг|мл|кг|вес|калькул", l): return "вопрос_по_дозировке"
    if re.search(r"диф|отличи|вероятн|симптом", l): return "дифдиагностика"
    if re.search(r"протокол|мкб|нозолог|критери|показани|госпитал", l): return "поиск_протокола"
    return "общий_вопрос"

# Какие разделы протокола нужны под вопрос. Замер на золотом наборе показал, что
# без этого «правильный протокол, но не тот кусок текста» — половина промахов:
# вопрос про лечение вытаскивал определение и жалобы, и модель честно отвечала
# «в контексте нет информации о лечении».
_REFERRAL = re.compile(
    r"госпитализ|направлен|показания к операц|когда в стационар|в стационар", re.I)
# «рецидив» здесь больше не маркер профилактики: «лечение рецидивирующего
# ларингита» и «какие симптомы при рецидиве» уходили в раздел профилактики
# (проверено запросом). Профилактика — это когда спрашивают про профилактику.
_PREVENTION = re.compile(r"профилактик|предотврат|диспансерн|вакцин", re.I)
_TREATMENT = re.compile(
    # «леч» вместо «лечен»: врач пишет «чем лечить», а не «лечение» — форма
    # глагола не совпадала, вопрос про тактику уходил в общий поиск и выдача
    # заполнялась определением (проверено живым запросом).
    r"леч|терапи|антибиотик|препарат|доз|мг/кг|\bмг\b|\bмл\b|операц|тонзиллэктом|аденотом|"
    r"хирург|тактик|назнач|вскрыт|дренир|купир|что делать|неотложн|ведени|"
    r"антибактериальн|капл|спрей|промыв|физиотерап", re.I)
_DIAGNOSTICS = re.compile(
    r"диагност|симптом|жалоб|осмотр|обследован|критери|признак|\bмкб\b|дифференц|проявлен|"
    r"скрининг|анамнез|отоскоп|аудиометр|тимпано|кровотечен|выделени|зуд|температур|лихорадк|"
    # «залож» и «тяжест» — жалобы («заложен нос», «тяжесть в области лица»):
    # без них вопрос-симптом без названия болезни не маршрутизировался вообще,
    # и в топ-6 шло определение вместо диагностики (§12).
    r"перепонк|проход|дыхани|отек|отёк|картин|боль|залож|тяжест", re.I)
_DEFINITION = re.compile(r"определен|этиологи|патогенез|классификац|что такое|распространенн", re.I)


def section_hint(query: str) -> list[str]:
    """Разделы протокола, релевантные вопросу (пусто — если вопрос общий).

    Порядок проверок — не случайный: «когда госпитализировать» содержит
    «госпитализ», но не должно уходить в лечение, а «профилактика рецидивов»
    не должна попадать в диагностику. Сначала самые узкие темы.
    """
    l = query or ""
    if _REFERRAL.search(l):
        return ["referral_criteria"]
    if _PREVENTION.search(l):
        return ["prevention"]
    if _TREATMENT.search(l):
        return ["treatment"]
    if _DIAGNOSTICS.search(l):
        return ["diagnostics"]
    if _DEFINITION.search(l):
        return ["definition"]
    return []


# Нозология из текста вопроса. Правила идут от специфичного к общему, побеждает
# ПЕРВОЕ совпадение: «хронический отит» должно опережать общее «отит», а «травма
# гортани» — симптом «осиплость» (иначе «осиплость после удара в шею» уходило в
# ларингит). Если ни одно правило не сработало — возвращаем None: лучше не бустить
# ничего, чем бустить чужой протокол (см. docs/RETRIEVAL_EVAL.md §11).
_NOSOLOGY_RULES: tuple[tuple[str, str], ...] = (
    (r"опухол|остеом|хондром|новообразовани\w* (нос|пазух)",
     "Доброкачественные остеогенные и хондрогенные опухоли носа и околоносовых пазух"),
    (r"грибков|отомикоз|плесен|мицели", "Грибковый отит"),
    (r"отосклероз|стремен", "Отосклероз"),
    (r"меньер", "Болезнь Меньера"),
    (r"нейросенсорн|сенсоневральн", "Нейросенсорная тугоухость у взрослых"),
    (r"потер\w* слуха от шум|после концерта|громк\w* музык|беруш|производственн\w* шум|"
     r"шумов\w* (воздейств|нагрузк)", "Потеря слуха, вызванная шумом"),
    (r"эпиглоттит|круп\b|лающ\w* кашел|стридор|инспираторн\w*",
     "Острый обструктивный ларингит [круп], эпиглоттит, постинтубационный отек гортани"),
    (r"паратонзиллярн|тризм|флегмон\w* (шеи|глотки)", "Паратонзиллярный абсцесс"),
    (r"аденоид", "Гипертрофия аденоидов"),
    (r"полип", "Полипозный риносинусит"),
    (r"травм\w* гортан|удар\w* в шею|травм\w* шеи|повреждени\w* гортан", "Травма гортани"),
    (r"травм\w* нос|удар\w* нос|сломан\w* нос|кровотечени\w* из нос", "Травма носа"),
    (r"травм\w* ух|удар\w* по уху|повреждени\w* уха|кров\w* из (слухового )?прохода", "Травма уха"),
    (r"перегородк|искривлен\w* нос|деформаци\w* нос", "Деформация перегородки носа"),
    # Симптомы без названия болезни — только те, что на замере давали промах,
    # и только с высокой специфичностью (docs/RETRIEVAL_EVAL.md §12):
    # * козелок и оттягивание раковины — наружный отит, а не средний;
    # * тризм («трудно открывать рот») — паратонзиллярный абсцесс; правило
    #   стоит ПОСЛЕ травм, иначе «трудно открывать рот после удара в шею»
    #   получило бы абсцесс вместо травмы гортани;
    # * «охрип» — та же ось, что «осиплость», но словоформа не совпадала.
    # Симптомы, которые и без правила уже стоят первыми (наклон+пазухи,
    # зуд в носу, триада Меньера, храп у ребёнка), сознательно НЕ добавлены:
    # нулевой выигрыш по метрике и лишний риск чужой нозологии.
    (r"козел(?:ок|к)|нажати\w*\s+на\s+ухо|оттягива\w*\s+(?:ушн\w*\s+)?раковин\w*|"
     r"пальпаци\w*\s+(?:ушн\w*\s+)?раковин\w*", "Наружные отиты"),
    (r"тризм|(?:трудн\w*|больно|невозможно|не\s+может)\s+(?:\w+\s+){0,2}открыв\w*\s+рот",
     "Паратонзиллярный абсцесс"),
    (r"наружн\w* отит|отит\w* наружн", "Наружные отиты"),
    (r"хроническ\w* (средн\w* )?отит|перфораци\w* перепонк|дырк\w* в перепонк|запах из уха",
     "Хронический средний отит"),
    (r"отит", "Отит средний острый"),
    (r"хроническ\w* тонзиллит|част\w* ангин|рецидивирующ\w* ангин|тонзиллэктом",
     "Хронический тонзиллит"),
    (r"тонзиллит|ангин|миндалин|гланд", "Острый тонзиллит и фарингит"),
    (r"синусит|гайморит|пазух", "Острый синусит"),
    (r"аллергическ\w* ринит|чиха|аллерги\w* насморк", "Аллергический ринит"),
    (r"ларингит|осиплост|охрип|голос пропал|потеря голоса|афони", "Острый ларингит"),
)
_NOSOLOGY_RX = tuple((re.compile(rx, re.I), nos) for rx, nos in _NOSOLOGY_RULES)


def nosology_hint(query: str) -> str | None:
    """Нозология, о которой спрашивают, или None (не уверены).

    Зачем: косинусы e5 на клинических вопросах сжаты в 0.80–0.87, и разница
    между «острым средним отитом» и «острым синуситом» тонет в шуме — в топ-5
    шли чужие протоколы с тем же разделом. Раздел уже маршрутизируется
    (section_hint), нозология — нет; на замере это стоило 4 из 22 вопросов
    hold-out, где правильный протокол стоял на 6–13 месте.

    Правила читаются из названий протоколов корпуса и общепринятых
    клинических синонимов («ангина» → тонзиллит, «круп» → обструктивный
    ларингит), а не из формулировок набора замера. Молчание (None) —
    осознанная часть контракта: неверная нозология хуже отсутствия.
    """
    l = (query or "").lower()
    if not l.strip():
        return None
    for rx, nos in _NOSOLOGY_RX:
        if rx.search(l):
            return nos
    return None


def retrieve(store, query: str, k: int = 6, filters: dict | None = None,
             general_cap: int | None = None) -> list[dict]:
    """Единая точка поиска: стор + маршрутизация вопроса по разделам и нозологии.

    Одну и ту же функцию используют приложение и замер — метрика измеряет
    ровно то, что видит врач. Реранкер (если включён) забирает больше
    кандидатов, чем нужно, и оставляет k лучших; score в выдаче остаётся
    честным косинусом, поэтому порог отказа не меняется.

    Явный фильтр по нозологии от клиента главнее догадки: если врач выбрал
    протокол руками, подсказку не подмешиваем.
    """
    from . import reranker

    n = max(k, int(reranker.settings.RERANK_TOP_N)) if reranker.enabled() else k
    nos = None if (filters or {}).get("nosology") else nosology_hint(query)
    chunks = store.search(query, k=n, filters=filters, nosology_boost=nos,
                          section_boost=section_hint(query), general_cap=general_cap)
    return reranker.rerank(query, chunks, k)
